INSERT INTO catalogo_cuentas (codigo, nombre, nivel, naturaleza, tipo, padre_codigo, es_hoja, activo)
SELECT t.codigo,
       t.nombre,
       CHAR_LENGTH(t.codigo) AS nivel,
       t.naturaleza,
       CASE
         WHEN t.codigo LIKE '1%' THEN 'ACTIVO'
         WHEN t.codigo LIKE '2%' THEN 'PASIVO'
         WHEN t.codigo LIKE '3%' THEN 'PATRIMONIO'
         WHEN t.codigo LIKE '4%' THEN 'RESULTADO_DEUDOR'
         WHEN t.codigo LIKE '5%' THEN 'RESULTADO_ACREEDOR'
         ELSE 'ORDEN'
       END AS tipo,
       CASE
         WHEN CHAR_LENGTH(t.codigo) > 2 THEN LEFT(t.codigo, CHAR_LENGTH(t.codigo) - 2)
         ELSE NULL
       END AS padre_codigo,
       CASE WHEN (SELECT COUNT(*) FROM cat_tmp_carga h
                   WHERE h.codigo <> t.codigo AND h.codigo LIKE t.codigo || '%') = 0
            THEN 1 ELSE 0 END AS es_hoja,
       1 AS activo
FROM cat_tmp_carga t
WHERE NOT EXISTS (SELECT 1 FROM catalogo_cuentas c WHERE c.codigo = t.codigo);

